export const iconSvg = (name) =>
  `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${ICONS[name] || ''}</svg>`;

export const icon = (name) => h('span', { 'data-icon': name, html: iconSvg(name) });

/** Fill every static <span data-icon="…"> in the page. */
export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]:empty').forEach((el) => (el.innerHTML = iconSvg(el.dataset.icon)));
}

export function timeAgo(iso) {
  if (!iso) return '';
  const s = (Date.now() - Date.parse(iso)) / 1000;
  if (s < 45) return 'just now';
  if (s < 3600) return `${Math.round(s / 60)}m ago`;
  if (s < 86400) return `${Math.round(s / 3600)}h ago`;
  return new Date(iso).toLocaleDateString(undefined, { day: 'numeric', month: 'short' });
}

